/** Extracts the slides, the page language and the page chrome of the reference deck. */
export function extractReference(html) {
  const root = parseHtml(html);
  const claimed = new Set();
  const structure = [];
  const htmlElement = find(root, (element) => element.name === 'html')[0];
  const articles = find(root, (element) => element.name === 'article' && hasClass(element, 'deck-slide'));
  const slides = articles.map((article, index) => extractSlide(article, index + 1, claimed, structure));

  const chrome = [];
  for (const region of PAGE_CHROME) {
    for (const element of find(root, region.match)) {
      for (const node of descendants(element)) {
        if (node.type === 'text') {
          claimed.add(node);
        }
      }
      chrome.push({label: region.label, text: spacedText(element)});
    }
  }
  for (const meta of find(root, (element) => element.name === 'meta' && element.attributes.name === 'robots')) {
    chrome.push({label: 'robots meta', text: meta.attributes.content ?? ''});
  }
  for (const comment of root.comments) {
    chrome.push({label: 'comment', text: comment});
  }

  const unclaimed = [];
  for (const node of descendants(root)) {
    if (node.type === 'text' && node.text.trim() !== '' && !claimed.has(node)) {
      unclaimed.push({path: pathOf(node.parent), text: collapse(node.text)});
    }
  }
  return {language: htmlElement?.attributes.lang ?? null, slides, chrome, structure, unclaimed};
}

function extractSlide(article, position, claimed, structure) {
  const note = (message) => structure.push(`slide ${position}: ${message}`);
  const only = (parent, predicate, description) => {
    const matches = elementChildren(parent).filter(predicate);
    if (matches.length !== 1) {
      note(`expected one ${description} in ${pathOf(parent)}, found ${matches.length}`);
      return null;
    }
    return matches[0];
  };
  const byClass = (name, className) => (element) => element.name === name && hasClass(element, className);
  const plain = (element, field) => {
    if (element === null) {
      return null;
    }
    const parts = inlineParts(element, claimed);
    if (parts.some((part) => part.text === undefined)) {
      note(`${field} holds markup (${partsToMarkup(parts)}); only text is expected`);
    }
    return partsToMarkup(parts);
  };

  const layouts = classesOf(article).filter((name) => name.startsWith('slide-layout-'));
  const slide = {
    position,
    layout: layouts.length === 1 ? layouts[0].slice('slide-layout-'.length) : null,
    register: null,
    wordmark: null,
    title: null,
    lead: null,
    footer: null,
    counter: null,
    notesLabel: null,
    notes: null,
  };
  if (layouts.length !== 1) {
    note(`expected one slide-layout-* class, found ${layouts.length}`);
  }
  if (article.attributes.id !== `slide-${position}`) {
    note(`id is ${JSON.stringify(article.attributes.id)}, expected "slide-${position}"`);
  }
  if (article.attributes['aria-labelledby'] !== `title-${position}`) {
    note(`aria-labelledby is ${JSON.stringify(article.attributes['aria-labelledby'])}, expected "title-${position}"`);
  }

  const canvas = only(article, byClass('div', 'slide-canvas'), 'div.slide-canvas');
  if (canvas !== null) {
    const register = only(canvas, byClass('div', 'slide-register'), 'div.slide-register');
    if (register !== null) {
      const spans = elementChildren(register);
      if (spans.length !== 2 || spans[0].name !== 'span' || !byClass('span', 'wordmark')(spans[1])) {
        note('the register is expected to hold a span and a span.wordmark');
      } else {
        slide.register = plain(spans[0], 'register');
        slide.wordmark = plain(spans[1], 'wordmark');
      }
    }
    const title = only(canvas, byClass('h2', 'slide-title'), 'h2.slide-title');
    if (title !== null) {
      slide.title = inlineParts(title, claimed);
      if (title.attributes.id !== `title-${position}`) {
        note(`the title id is ${JSON.stringify(title.attributes.id)}, expected "title-${position}"`);
      }
    }
    const lead = only(canvas, byClass('p', 'slide-lead'), 'p.slide-lead');
    if (lead !== null) {
      slide.lead = inlineParts(lead, claimed);
    }
    const content = only(canvas, byClass('div', 'slide-content'), 'div.slide-content');
    if (content !== null && slide.layout !== null) {
      extractContent(slide, content, claimed, note, only, plain);
    }
    const footer = only(canvas, (element) => element.name === 'footer' && hasClass(element, 'slide-footer'), 'footer.slide-footer');
    if (footer !== null) {
      const spans = elementChildren(footer);
      if (spans.length !== 2 || spans.some((span) => span.name !== 'span')) {
        note('the footer is expected to hold two spans');
      } else {
        slide.footer = plain(spans[0], 'footer');
        slide.counter = plain(spans[1], 'footer counter');
      }
    }
  }

  const aside = only(article, byClass('aside', 'slide-notes'), 'aside.slide-notes');
  if (aside !== null) {
    const [label, ...rest] = aside.children;
    if (label === undefined || label.type !== 'element' || label.name !== 'strong') {
      note('the notes aside is expected to open with a strong label');
    } else {
      slide.notesLabel = plain(label, 'notes label');
      const notes = inlineParts({children: rest}, claimed);
      if (notes.some((part) => part.text === undefined)) {
        note(`the notes hold markup (${partsToMarkup(notes)}); only text is expected`);
      }
      slide.notes = notes.filter((part) => part.text !== undefined).map((part) => part.text).join('');
    }
  }
  return slide;
}

function extractContent(slide, content, claimed, note, only, plain) {
  const children = elementChildren(content);
  const strayText = content.children.some((child) => child.type === 'text' && child.text.trim() !== '');
  if (strayText) {
    note('the slide content holds loose text');
  }
  const layout = slide.layout;
  if (layout === 'statement') {
    if (children.length !== 0) {
      note('a statement slide is expected to have empty content');
    }
  } else if (layout === 'cover' || layout === 'closing') {
    const horizon = only(content, (element) => element.name === 'div' && hasClass(element, 'horizon'), 'div.horizon');
    if (horizon !== null) {
      slide.horizon = {
        ariaHidden: horizon.attributes['aria-hidden'] ?? null,
        spans: elementChildren(horizon).filter((element) => element.name === 'span').length,
        text: collapse(textContent(horizon)),
      };
    }
    if (children.length !== 1) {
      note(`the ${layout} content is expected to hold only the horizon ornament`);
    }
  } else if (Object.hasOwn(COLUMN_COUNTS, layout)) {
    const columns = only(content, (element) => element.name === 'div' && hasClass(element, 'slide-columns'), 'div.slide-columns');
    if (columns !== null) {
      slide.columnClasses = classesOf(columns);
      slide.columns = elementChildren(columns).map((column, index) => {
        const [heading, text, ...extra] = elementChildren(column);
        if (!hasClass(column, 'slide-column') || heading?.name !== 'h3' || text?.name !== 'p' || extra.length > 0) {
          note(`column ${index + 1} is expected to be div.slide-column holding an h3 and a p`);
        }
        return {
          heading: heading ? plain(heading, `column ${index + 1} heading`) : null,
          text: text ? inlineParts(text, claimed) : null,
        };
      });
    }
  } else if (layout === 'attributes') {
    const list = only(content, (element) => element.name === 'div' && hasClass(element, 'slide-attributes'), 'div.slide-attributes');
    if (list !== null) {
      slide.items = elementChildren(list).map((item, index) => {
        const [label, ...rest] = item.children;
        if (item.name !== 'p' || label?.type !== 'element' || label.name !== 'strong') {
          note(`attribute ${index + 1} is expected to be a p opening with a strong label`);
          return {label: null, text: null};
        }
        const text = inlineParts({children: rest}, claimed);
        if (text.some((part) => part.text === undefined)) {
          note(`attribute ${index + 1} text holds markup`);
        }
        return {label: plain(label, `attribute ${index + 1} label`), text: partsToMarkup(text)};
      });
    }
  } else if (layout === 'palette') {
    const list = only(content, (element) => element.name === 'div' && hasClass(element, 'slide-swatches'), 'div.slide-swatches');
    if (list !== null) {
      slide.swatches = elementChildren(list).map((swatch, index) => {
        const [chip, caption, ...extra] = elementChildren(swatch);
        const [name, br, value, ...more] = caption?.children ?? [];
        const shaped = chip !== undefined && hasClass(chip, 'slide-swatch') && caption?.name === 'p' && extra.length === 0 &&
          name?.type === 'element' && name.name === 'strong' && br?.type === 'element' && br.name === 'br' &&
          value?.type === 'text' && more.length === 0;
        if (!shaped) {
          note(`swatch ${index + 1} is expected to be a div.slide-swatch and a p holding strong, br and the value`);
          return {name: null, value: null, style: null};
        }
        claimed.add(value);
        const style = /^background:\s*(#[0-9A-Fa-f]{3,8})\s*;?$/.exec(chip.attributes.style ?? '');
        return {name: plain(name, `swatch ${index + 1} name`), value: value.text, style: style ? style[1] : null};
      });
    }
  } else if (layout === 'type') {
    const demo = only(content, (element) => element.name === 'div' && hasClass(element, 'type-demo'), 'div.type-demo');
    if (demo !== null) {
      slide.samples = elementChildren(demo).map((group) => {
        const [eyebrow, sample] = elementChildren(group);
        return {
          eyebrow: eyebrow ? plain(eyebrow, 'type eyebrow') : null,
          className: sample ? (sample.attributes.class ?? null) : null,
          sample: sample ? partsToMarkup(inlineParts(sample, claimed)) : null,
        };
      });
    }
  } else if (layout === 'wordmark') {
    const demo = only(content, (element) => element.name === 'div' && hasClass(element, 'slide-columns'), 'div.slide-columns');
    if (demo !== null) {
      slide.markSamples = elementChildren(demo).map((mark) => ({
        classes: classesOf(mark),
        text: plain(mark, 'wordmark sample'),
      }));
    }
  } else {
    note(`the layout ${JSON.stringify(layout)} is not one this check knows how to read`);
  }
}

