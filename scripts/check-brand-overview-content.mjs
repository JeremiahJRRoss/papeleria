function lineIndex(source) {
  const starts = [0];
  for (let index = 0; index < source.length; index += 1) {
    if (source[index] === '\n') {
      starts.push(index + 1);
    }
  }
  return (offset) => {
    let low = 0;
    let high = starts.length - 1;
    while (low < high) {
      const middle = Math.ceil((low + high) / 2);
      if (starts[middle] <= offset) {
        low = middle;
      } else {
        high = middle - 1;
      }
    }
    return low + 1;
  };
}

/**
 * Parses a manifest the way IC01 requires: one YAML document, unique string
 * keys, no anchors, aliases, merge keys or explicit tags. Returns the problems
 * rather than throwing, so a caller can report all of them at once.
 */
export function parseManifest(source) {
  const lineAt = lineIndex(source);
  const problems = [];
  const parsed = parseAllDocuments(source, {prettyErrors: true});
  const documents = Array.isArray(parsed) ? parsed : [];
  if (documents.length !== 1) {
    problems.push(`holds ${documents.length} YAML documents; exactly one is required (IC01)`);
    return {document: null, data: null, lineAt, problems};
  }
  const [document] = documents;
  for (const error of document.errors) {
    problems.push(`line ${error.linePos?.[0]?.line ?? '?'}: ${error.code}: ${error.message.split('\n')[0]}`);
  }
  for (const warning of document.warnings) {
    problems.push(`line ${warning.linePos?.[0]?.line ?? '?'}: ${warning.code}: ${warning.message.split('\n')[0]}`);
  }
  const at = (node) => (node?.range ? `line ${lineAt(node.range[0])}` : 'line ?');
  visit(document, {
    Alias(_, node) {
      problems.push(`${at(node)}: the alias *${node.source} is not allowed (IC01)`);
    },
    Node(_, node) {
      if (node.anchor) {
        problems.push(`${at(node)}: the anchor &${node.anchor} is not allowed (IC01)`);
      }
      if (node.tag) {
        problems.push(`${at(node)}: the explicit tag ${node.tag} is not allowed (IC01)`);
      }
    },
    Pair(_, pair) {
      if (!isScalar(pair.key) || typeof pair.key.value !== 'string') {
        problems.push(`${at(pair.key)}: every mapping key must be a string (IC01)`);
      } else if (pair.key.value === '<<') {
        problems.push(`${at(pair.key)}: merge keys are not allowed (IC01)`);
      }
    },
  });
  const data = problems.length === 0 ? document.toJS() : null;
  if (problems.length === 0 && (data === null || typeof data !== 'object' || Array.isArray(data))) {
    problems.push('the manifest must be a mapping');
  }
  return {document, data, lineAt, problems};
}

export function readPiece(directory) {
  const manifestFile = join(directory, 'papeleria.yaml');
  if (!existsSync(manifestFile)) {
    throw new UsageError(`${manifestFile} is missing`);
  }
  if (existsSync(join(directory, 'papeleria.json'))) {
    throw new UsageError(`${directory} holds both papeleria.yaml and papeleria.json; a piece has exactly one manifest (IC01)`);
  }
  const source = readFileSync(manifestFile, 'utf8');
  const manifest = parseManifest(source);
  if (manifest.problems.length > 0) {
    throw new UsageError(manifest.problems.map((problem) => `${manifestFile}: ${problem}`).join('\n'));
  }
  const readText = (relativePath) => {
    const file = join(directory, relativePath);
    return existsSync(file) ? readFileSync(file, 'utf8') : null;
  };
  return {directory, manifestFile, ...manifest, readText};
}

function readDefaultWordmark(file) {
  if (!existsSync(file)) {
    throw new UsageError(`${file} is missing`);
  }
  let brand;
  try {
    brand = JSON.parse(readFileSync(file, 'utf8'));
  } catch (cause) {
    throw new UsageError(`cannot parse ${file}: ${cause.message}`);
  }
  if (typeof brand?.wordmark !== 'string') {
    throw new UsageError(`${file} has no string "wordmark"`);
  }
  return brand.wordmark;
}

