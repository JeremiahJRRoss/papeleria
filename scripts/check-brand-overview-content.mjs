/** The built core, whose Markdown functions are the ones a build publishes with (D162). */
export async function loadCore() {
  const entry = join(applicationRoot, 'lib', 'src', 'core', 'index.js');
  if (!existsSync(entry)) {
    throw new UsageError(`${relative(applicationRoot, entry)} is missing; run npm run build first, because the render level uses the product's Markdown functions (D162)`);
  }
  return import(pathToFileURL(entry).href);
}

function createRenderers(core) {
  const externalLinkLabel = core.loadStrings('en').external_link;
  return {
    // The product's renderers, exactly as resolve calls them: inline for a title or lead,
    // block for column text (base level 4) and slide notes (base level 3).
    inline: (text) => core.renderInlineMarkdown(text, {externalLinkLabel}).html,
    block: (text, baseLevel = 3) => core.renderMarkdown(text, {baseLevel, docId: 'check', externalLinkLabel}).html,
    // The product leaves the typographer off. These two markdown-it copies differ only in that
    // setting, so comparing them shows whether the text depends on it.
    plain: new MarkdownIt({html: false}).use(footnote),
    typographer: new MarkdownIt({html: false, typographer: true}).use(footnote),
  };
}

export function escapeHtml(text) {
  return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

function firstDifference(expected, actual) {
  let index = 0;
  while (index < expected.length && index < actual.length && expected[index] === actual[index]) {
    index += 1;
  }
  const excerpt = (text) => JSON.stringify(text.slice(Math.max(0, index - 20), index + 30));
  return `at character ${index + 1}: expected …${excerpt(expected)}… found …${excerpt(actual)}…`;
}

function describe(expected, actual) {
  if (typeof expected === 'string' && typeof actual === 'string' && (expected.length > 60 || actual.length > 60)) {
    return firstDifference(expected, actual);
  }
  return `expected ${JSON.stringify(expected)}, found ${JSON.stringify(actual)}`;
}

/** Compares a piece with the reference. Returns every difference found, and counts for the report. */
export function compareContent(reference, piece, defaultWordmark, core) {
  const differences = [];
  const counts = {sourceFields: 0, renderedFields: 0, notesFiles: 0, notesParagraphs: 0, urlParagraphs: 0};
  const renderers = createRenderers(core);
  const {data, document, lineAt} = piece;
  const manifestName = 'papeleria.yaml';
  const lineOf = (path) => {
    for (let depth = path.length; depth >= 0; depth -= 1) {
      const node = depth === 0 ? document.contents : document.getIn(path.slice(0, depth), true);
      if (node?.range) {
        return lineAt(node.range[0]);
      }
    }
    return null;
  };
  const at = (path) => `${manifestName}:${lineOf(path) ?? '?'}`;
  const differ = (where, message) => differences.push(`${where}: ${message}`);

  for (const problem of reference.structure) {
    differ('reference', problem);
  }
  for (const node of reference.unclaimed) {
    differ('reference', `text that no manifest field or documented template content claims, at ${node.path}: ${JSON.stringify(node.text)}`);
  }

  // The render level runs only once the source level agrees, so one defect is reported once.
  // A Markdown field must render to the kit's fragment; a plain-string field must come
  // through markdown-it unchanged, so the result does not depend on how the renderer
  // treats it. Either way, the typographer must change nothing.
  const checkRendered = (label, path, value, expectedParts, block = false) => {
    counts.renderedFields += 1;
    let rendered = renderers.inline(value);
    if (block) {
      // Column text is block Markdown (D150): it must render as exactly one paragraph.
      const html = renderers.block(value, 4);
      const paragraph = /^<p>((?:(?!<\/?p>)[\s\S])*)<\/p>\n$/.exec(html);
      if (paragraph === null) {
        differ(`${label}, ${at(path)}`, `the product renders ${JSON.stringify(html)}; the kit has one paragraph, ${JSON.stringify(`<p>${partsToMarkup(expectedParts)}</p>`)}`);
        return;
      }
      rendered = paragraph[1];
    }
    if (expectedParts === null) {
      if (rendered !== escapeHtml(value)) {
        differ(`${label}, ${at(path)}`, `this plain-string field would render as ${JSON.stringify(rendered)} if treated as Markdown; keep Markdown syntax out of it`);
        return;
      }
    } else if (partsToMarkup(renderedParts(rendered)) !== partsToMarkup(expectedParts)) {
      differ(`${label}, ${at(path)}`, `the product renders ${JSON.stringify(rendered)}; the kit has ${JSON.stringify(partsToMarkup(expectedParts))}`);
      return;
    }
    if (renderers.typographer.renderInline(value) !== renderers.plain.renderInline(value)) {
      differ(`${label}, ${at(path)}`, "markdown-it's typographer would change this text; write typographic characters as Unicode (D55)");
    }
  };
  const checkBrackets = (label, value) => {
    if (/[[\]]/.test(value)) {
      differ(label, 'holds bracketed text; the kit has none, and an unescaped label is an R01 placeholder');
    }
  };
  const checkPlain = (label, path, value, expected) => {
    counts.sourceFields += 1;
    if (typeof value !== 'string') {
      differ(`${label}, ${at(path)}`, `expected the text ${JSON.stringify(expected)}, found ${JSON.stringify(value)}`);
      return;
    }
    checkBrackets(`${label}, ${at(path)}`, value);
    if (value !== expected) {
      differ(`${label}, ${at(path)}`, describe(expected, value));
      return;
    }
    checkRendered(label, path, value, null);
  };
  const checkMarkdown = (label, path, value, expectedParts, block = false) => {
    counts.sourceFields += 1;
    const expected = partsToSource(expectedParts);
    if (typeof value !== 'string') {
      differ(`${label}, ${at(path)}`, `expected the text ${JSON.stringify(expected)}, found ${JSON.stringify(value)}`);
      return;
    }
    const normalized = value.replace(/\r\n/g, '\n');
    checkBrackets(`${label}, ${at(path)}`, normalized);
    // A backslash escape of ASCII punctuation is how Markdown writes a literal character,
    // so it is the same text at source level; the render level then has the last word.
    if (normalized.replace(MARKDOWN_ESCAPE, '$1') !== expected) {
      const hint = / {2,}\n/.test(normalized) ? '; write each hard break as a backslash ending the line, not as trailing spaces (D55)' : '';
      differ(`${label}, ${at(path)}`, `${describe(expected, normalized)}${hint}`);
      return;
    }
    checkRendered(label, path, normalized, expectedParts, block);
  };

  // Top level.
  const keys = Object.keys(data);
  for (const key of keys) {
    if (!MANIFEST_KEYS.includes(key)) {
      differ(`manifest ${key}, ${at([key])}`, `unexpected key; this piece carries ${MANIFEST_KEYS.join(', ')} only (D55)`);
    }
  }
  for (const key of MANIFEST_KEYS) {
    if (!keys.includes(key)) {
      differ(`manifest, ${at([])}`, `the key ${key} is missing`);
    }
  }
  for (const [key, expected] of Object.entries(FIXED_VALUES)) {
    if (keys.includes(key) && data[key] !== expected) {
      differ(`manifest ${key}, ${at([key])}`, describe(expected, data[key]));
    }
  }
  if (keys.includes('language') && data.language !== reference.language) {
    differ(`manifest language, ${at(['language'])}`, `the reference page language is ${JSON.stringify(reference.language)}, found ${JSON.stringify(data.language)}`);
  }

  const referenceSlides = reference.slides;
  const edition = referenceSlides[0]?.footer ?? null;
  if (keys.includes('edition') && edition !== null) {
    checkPlain('manifest edition', ['edition'], data.edition, edition);
  }
  if (keys.includes('register') && referenceSlides[0]?.register != null) {
    checkPlain('manifest register', ['register'], data.register, referenceSlides[0].register);
  }
  if (keys.includes('title') && referenceSlides[0]?.title != null) {
    checkMarkdown('manifest title (the cover title)', ['title'], data.title, referenceSlides[0].title);
  }

  const slides = Array.isArray(data.slides) ? data.slides : [];
  if (!Array.isArray(data.slides)) {
    differ(`manifest slides, ${at(['slides'])}`, 'expected a list of slides');
  }
  if (referenceSlides.length !== 16) {
    differ('reference', `expected 16 slides, found ${referenceSlides.length}`);
  }
  if (slides.length !== referenceSlides.length) {
    differ(`manifest slides, ${at(['slides'])}`, `the reference has ${referenceSlides.length} slides, the manifest ${slides.length}`);
  }
  const expectedLayouts = referenceSlides.map((slide) => slide.layout).join(', ');
  const actualLayouts = slides.map((slide) => slide?.layout).join(', ');
  if (expectedLayouts !== actualLayouts) {
    differ(`manifest slides, ${at(['slides'])}`, `layout sequence differs: the reference has ${expectedLayouts}; the manifest has ${actualLayouts}`);
  }

  const count = referenceSlides.length;
  for (let index = 0; index < Math.min(slides.length, count); index += 1) {
    const expected = referenceSlides[index];
    const slide = slides[index];
    const number = index + 1;
    const nn = String(number).padStart(2, '0');
    const base = ['slides', index];
    const label = (field) => `slide ${number} (${expected.layout}) ${field}`;
    if (slide === null || typeof slide !== 'object' || Array.isArray(slide)) {
      differ(`slide ${number}, ${at(base)}`, 'expected a mapping');
      continue;
    }

    const allowed = [...SLIDE_KEYS, ...(LAYOUT_KEYS[slide.layout] ?? [])];
    for (const key of Object.keys(slide)) {
      if (!allowed.includes(key)) {
        differ(`${label(key)}, ${at([...base, key])}`, `unexpected key for the ${slide.layout} layout`);
      }
    }
    if (slide.layout !== expected.layout) {
      differ(`${label('layout')}, ${at([...base, 'layout'])}`, describe(expected.layout, slide.layout));
    }

    // The template writes the register, the wordmark and the counter on every slide.
    if (expected.register !== data.register) {
      differ(`${label('register')}`, `the reference register ${JSON.stringify(expected.register)} differs from the manifest register`);
    }
    if (expected.wordmark !== defaultWordmark) {
      differ(`${label('wordmark')}`, `the reference shows ${JSON.stringify(expected.wordmark)}; with no wordmark key the theme default ${JSON.stringify(defaultWordmark)} shows (D04)`);
    }
    const counter = `${nn} / ${count}`;
    if (expected.counter !== counter) {
      differ(`${label('footer counter')}`, `the renderer writes ${JSON.stringify(counter)}; the reference has ${JSON.stringify(expected.counter)}`);
    }
    if (expected.notesLabel !== NOTES_LABEL) {
      differ(`${label('notes label')}`, describe(NOTES_LABEL, expected.notesLabel));
    }

    if (expected.title !== null) {
      checkMarkdown(label('title'), [...base, 'title'], slide.title, expected.title);
    }
    if (expected.lead !== null) {
      checkMarkdown(label('lead'), [...base, 'lead'], slide.lead, expected.lead);
    }

    // The footer falls back to the edition; writing the edition out again is redundant.
    if (slide.footer === undefined) {
      if (expected.footer !== data.edition) {
        differ(`${label('footer')}, ${at(base)}`, `no footer, so the edition ${JSON.stringify(data.edition)} shows; the reference has ${JSON.stringify(expected.footer)}`);
      }
    } else {
      checkPlain(label('footer'), [...base, 'footer'], slide.footer, expected.footer);
      if (slide.footer === data.edition) {
        differ(`${label('footer')}, ${at([...base, 'footer'])}`, 'repeats the edition; omit it and the footer falls back to the edition (D55)');
      }
    }

    // R15 on each side: the manifest's own layout fixes its column count, and so does the reference's.
    const columns = Array.isArray(slide.columns) ? slide.columns : [];
    if (Object.hasOwn(COLUMN_COUNTS, slide.layout) && columns.length !== COLUMN_COUNTS[slide.layout]) {
      differ(`${label('columns')}, ${at([...base, 'columns'])}`, `the ${slide.layout} layout takes ${COLUMN_COUNTS[slide.layout]} columns (R15); the manifest gives ${columns.length}`);
    }
    if (Object.hasOwn(COLUMN_COUNTS, expected.layout)) {
      if ((expected.columns ?? []).length !== COLUMN_COUNTS[expected.layout]) {
        differ(`${label('columns')}`, `the reference ${expected.layout} slide has ${(expected.columns ?? []).length} columns`);
      }
      if (columns.length > (expected.columns ?? []).length) {
        differ(`${label('columns')}, ${at([...base, 'columns'])}`, `the manifest gives ${columns.length} columns; the reference has ${(expected.columns ?? []).length}`);
      }
      (expected.columns ?? []).forEach((column, position) => {
        const path = [...base, 'columns', position];
        const actual = columns[position] ?? {};
        for (const key of Object.keys(actual)) {
          if (key !== 'heading' && key !== 'text') {
            differ(`${label(`column ${position + 1} ${key}`)}, ${at([...path, key])}`, 'unexpected key; a column is {heading, text}');
          }
        }
        checkPlain(label(`column ${position + 1} heading`), [...path, 'heading'], actual.heading, column.heading);
        checkMarkdown(label(`column ${position + 1} text`), [...path, 'text'], actual.text, column.text, true);
      });
    }

    if (expected.layout === 'attributes') {
      const items = Array.isArray(slide.items) ? slide.items : [];
      if ((expected.items ?? []).length === 0) {
        differ(`${label('items')}`, 'the reference attributes slide has no items');
      }
      if (items.length !== (expected.items ?? []).length) {
        differ(`${label('items')}, ${at([...base, 'items'])}`, `the reference has ${(expected.items ?? []).length} items, the manifest ${items.length}`);
      }
      (expected.items ?? []).forEach((item, position) => {
        const path = [...base, 'items', position];
        const actual = items[position] ?? {};
        for (const key of Object.keys(actual)) {
          if (key !== 'label' && key !== 'text') {
            differ(`${label(`item ${position + 1} ${key}`)}, ${at([...path, key])}`, 'unexpected key; an item is {label, text}');
          }
        }
        checkPlain(label(`item ${position + 1} label`), [...path, 'label'], actual.label, item.label);
        checkPlain(label(`item ${position + 1} text`), [...path, 'text'], actual.text, item.text);
      });
    }

    if (expected.layout === 'palette') {
      const swatches = Array.isArray(slide.swatches) ? slide.swatches : [];
      if ((expected.swatches ?? []).length === 0) {
        differ(`${label('swatches')}`, 'the reference palette slide has no swatches');
      }
      if (swatches.length !== (expected.swatches ?? []).length) {
        differ(`${label('swatches')}, ${at([...base, 'swatches'])}`, `the reference has ${(expected.swatches ?? []).length} swatches, the manifest ${swatches.length}`);
      }
      (expected.swatches ?? []).forEach((swatch, position) => {
        const path = [...base, 'swatches', position];
        const actual = swatches[position] ?? {};
        for (const key of Object.keys(actual)) {
          if (key !== 'name' && key !== 'value') {
            differ(`${label(`swatch ${position + 1} ${key}`)}, ${at([...path, key])}`, 'unexpected key; the reference shows a name and a value only');
          }
        }
        if (swatch.style !== swatch.value) {
          differ(`${label(`swatch ${position + 1}`)}`, `the reference paints ${JSON.stringify(swatch.style)} but prints ${JSON.stringify(swatch.value)}`);
        }
        checkPlain(label(`swatch ${position + 1} name`), [...path, 'name'], actual.name, swatch.name);
        checkPlain(label(`swatch ${position + 1} value`), [...path, 'value'], actual.value, swatch.value);
      });
    }

    if (expected.layout === 'cover' || expected.layout === 'closing') {
      const horizon = expected.horizon;
      if (!horizon || horizon.ariaHidden !== 'true' || horizon.spans !== 4 || horizon.text !== '') {
        differ(label('horizon'), 'the ornament is expected to be four empty spans hidden from assistive technology');
      }
    }
    if (expected.layout === 'type') {
      const samples = expected.samples ?? [];
      if (JSON.stringify(samples) !== JSON.stringify(TYPE_SAMPLES)) {
        differ(label('type samples'), `the reference samples ${JSON.stringify(samples)} differ from the documented theme samples`);
      }
    }
    if (expected.layout === 'wordmark') {
      const marks = expected.markSamples ?? [];
      const shaped = marks.length === 2 && marks.every((mark) => mark.classes[0] === 'mark-demo' && mark.text === defaultWordmark) &&
        marks[1].classes.includes('reverse');
      if (!shaped) {
        differ(label('wordmark samples'), `expected mark-demo and mark-demo reverse showing ${JSON.stringify(defaultWordmark)}, found ${JSON.stringify(marks)}`);
      }
    }

    // Notes: a file per slide, holding the aside text without the label.
    const notesPath = `assets/text/${nn}-notes.md`;
    if (slide.notes !== notesPath) {
      differ(`${label('notes')}, ${at([...base, 'notes'])}`, `expected the file reference ${JSON.stringify(notesPath)}, found ${JSON.stringify(slide.notes)} (D55)`);
      continue;
    }
    if (expected.notes === null) {
      continue;
    }
    const text = piece.readText(notesPath);
    const notesLabel = `${label('notes')}, ${notesPath}`;
    if (text === null) {
      differ(notesLabel, 'the file is missing (R02)');
      continue;
    }
    counts.notesFiles += 1;
    checkBrackets(notesLabel, text);
    compareNotes(notesLabel, text, expected.notes, renderers, differ, counts);
  }

  return {differences, counts};
}

/**
 * A notes file holds one paragraph per line of the reference aside, the label
 * removed. The text is compared first, then the file's layout, and markdown-it
 * is asked last, once the text is known to be right, so one defect is reported
 * once.
 */
function compareNotes(where, text, referenceText, renderers, differ, counts) {
  const paragraphs = referenceText.split('\n').map(collapse).filter((line) => line !== '');
  counts.notesParagraphs += paragraphs.length;
  counts.urlParagraphs += paragraphs.filter((paragraph) => /https?:\/\//.test(paragraph)).length;
  let found = false;
  const report = (label, message) => {
    found = true;
    differ(label, message);
  };

  if (text.startsWith('\ufeff')) {
    report(where, 'starts with a byte-order mark; notes are plain UTF-8');
  }
  const normalized = text.replace(/^\ufeff/, '').replace(/\r\n/g, '\n');
  const blocks = normalized.split(/\n[ \t]*\n/).filter((block) => block.trim() !== '');
  const actual = blocks.map((block) => collapse(block).replace(MARKDOWN_ESCAPE, '$1'));
  if (actual.length !== paragraphs.length) {
    report(where, `the reference has ${paragraphs.length} paragraph(s), the file ${actual.length}`);
  }
  paragraphs.forEach((paragraph, index) => {
    if (actual[index] !== undefined && actual[index] !== paragraph) {
      report(`${where} paragraph ${index + 1}`, describe(paragraph, actual[index]));
    }
  });
  if (found) {
    return;
  }

  // Under white-space: pre-line a soft wrap would show as a line break, so a paragraph is one line.
  blocks.forEach((block, index) => {
    if (block.trim().includes('\n')) {
      report(`${where} paragraph ${index + 1}`, 'is wrapped over several lines; the notes keep line breaks (pre-line), so each paragraph is one line (D55)');
    }
  });
  const layout = [
    [/^\s/.test(normalized), 'starts with whitespace'],
    [/[ \t]+$/m.test(normalized), 'has trailing spaces'],
    [/\n[ \t]*\n[ \t]*\n/.test(normalized), 'separates paragraphs by more than one blank line'],
    [!normalized.endsWith('\n') || normalized.endsWith('\n\n'), 'does not end with exactly one newline'],
  ];
  for (const [broken, message] of layout) {
    if (broken) {
      report(where, `${message}; the layout is one paragraph per line, one blank line between, one final newline (D55)`);
    }
  }
  if (found) {
    return;
  }

  const expectedHtml = paragraphs.map((paragraph) => `<p>${escapeHtml(paragraph)}</p>\n`).join('');
  const rendered = renderers.block(normalized);
  if (rendered !== expectedHtml) {
    report(where, `the product turns part of the notes into markup: ${firstDifference(expectedHtml, rendered)}`);
  } else if (renderers.typographer.render(normalized) !== renderers.plain.render(normalized)) {
    report(where, "markdown-it's typographer would change the notes; write typographic characters as Unicode (D55)");
  }
}

