function report(pieceDirectory, referenceFile, reference, result, slideCount) {
  const show = (path) => {
    const shown = relative(process.cwd(), path);
    return shown === '' || shown.startsWith('..') ? path : shown;
  };
  const lines = [`brand-overview content: ${show(pieceDirectory)} against ${show(referenceFile)}`];
  lines.push(`  reference: ${reference.slides.length} slide(s); layouts ${reference.slides.map((slide) => slide.layout).join(', ')}`);
  lines.push(`  manifest: ${slideCount} slide(s)`);
  lines.push(
    `  compared: ${result.counts.sourceFields} field(s) at source level, ${result.counts.renderedFields} rendered by the product, ` +
      `${result.counts.notesFiles} notes file(s) holding ${result.counts.notesParagraphs} paragraph(s)`,
  );
  lines.push(`  unclaimed reference text: ${reference.unclaimed.length}`);
  lines.push('  page chrome, listed and not compared (template output; docs/REFERENCE_COMPATIBILITY.md):');
  for (const region of reference.chrome) {
    lines.push(`    ${region.label}: ${JSON.stringify(region.text)}`);
  }
  lines.push(
    `note: ${result.counts.urlParagraphs} notes paragraph(s) hold plain URLs, which stay text only while markdown-it's linkify ` +
      'is off; the reference shows them as text.',
  );
  if (result.differences.length === 0) {
    lines.push(`result: pass — ${slideCount} slides, 0 differences`);
  } else {
    lines.push(`result: FAIL — ${result.differences.length} difference(s)`);
    for (const difference of result.differences) {
      lines.push(`  ${difference}`);
    }
  }
  return lines.join('\n');
}

function parseArguments(argv) {
  const options = {piece: DEFAULT_PIECE, reference: DEFAULT_REFERENCE};
  for (let index = 0; index < argv.length; index += 1) {
    const flag = argv[index];
    if (flag === '--piece' || flag === '--reference') {
      const value = argv[index + 1];
      if (value === undefined) {
        throw new UsageError(`${flag} needs a path`);
      }
      options[flag.slice(2)] = resolve(value);
      index += 1;
    } else {
      throw new UsageError(`unknown argument ${JSON.stringify(flag)}`);
    }
  }
  return options;
}

async function main(argv) {
  const usage = 'usage: node scripts/check-brand-overview-content.mjs [--piece <dir>] [--reference <file>]';
  let options;
  try {
    options = parseArguments(argv);
  } catch (error) {
    process.stderr.write(`check-brand-overview-content: ${error.message}\n${usage}\n`);
    return 2;
  }
  // Exit 1 means differences were found and nothing else: an input that cannot
  // be read, and an internal failure, both exit 2.
  let reference;
  let piece;
  let defaultWordmark;
  let core;
  try {
    reference = readReference(options.reference);
    piece = readPiece(options.piece);
    defaultWordmark = readDefaultWordmark(BRAND_DEFAULT);
    core = await loadCore();
  } catch (error) {
    process.stderr.write(`check-brand-overview-content: ${error.message}\n`);
    return 2;
  }
  let result;
  try {
    result = compareContent(reference, piece, defaultWordmark, core);
    // The piece must also be one the product accepts, read the way a build reads it.
    const product = await core.readPiece({loaders: core.createNodeLoaders(options.piece)});
    result.differences.unshift(
      ...product.findings.map((finding) => `product, ${finding.file}:${finding.line ?? '-'}: ${finding.rule} ${finding.message}`),
    );
  } catch (error) {
    process.stderr.write(`check-brand-overview-content: internal failure, no result: ${error.stack ?? error}\n`);
    return 2;
  }
  const slideCount = Array.isArray(piece.data.slides) ? piece.data.slides.length : 0;
  process.stdout.write(`${report(options.piece, options.reference, reference, result, slideCount)}\n`);
  return result.differences.length === 0 ? 0 : 1;
}

const entryPath = process.argv[1];
if (entryPath !== undefined && import.meta.url === pathToFileURL(entryPath).href) {
  process.exitCode = await main(process.argv.slice(2));
}
