// HTML: a tokenizer and tree builder sufficient for generated, well-formed markup.

const VOID_ELEMENTS = new Set(['area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input', 'link', 'meta', 'source', 'track', 'wbr']);
const TOKEN = /<!--[\s\S]*?-->|<!doctype[^>]*>|<\/([a-z][a-z0-9]*)\s*>|<([a-z][a-z0-9]*)((?:\s+[^\s"'=<>/]+(?:\s*=\s*(?:"[^"]*"|'[^']*'|[^\s"'=<>`]+))?)*)\s*(\/?)>|([^<]+)/giy;
const ATTRIBUTE = /([^\s"'=<>/]+)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s"'=<>`]+)))?/g;
const NAMED_ENTITIES = {amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: '\u00a0'};

/** Decodes character references. An unknown named entity is an error, never a silent pass-through. */
export function decodeEntities(text) {
  return text.replace(/&(#[0-9]+|#[xX][0-9a-fA-F]+|[A-Za-z][A-Za-z0-9]*);/g, (whole, body) => {
    if (body.startsWith('#x') || body.startsWith('#X')) {
      return String.fromCodePoint(Number.parseInt(body.slice(2), 16));
    }
    if (body.startsWith('#')) {
      return String.fromCodePoint(Number.parseInt(body.slice(1), 10));
    }
    if (!Object.hasOwn(NAMED_ENTITIES, body)) {
      throw new UsageError(`the entity ${whole} has no decoding here; add it to NAMED_ENTITIES`);
    }
    return NAMED_ENTITIES[body];
  });
}

function parseAttributes(text) {
  const attributes = {};
  for (const match of text.matchAll(ATTRIBUTE)) {
    const value = match[2] ?? match[3] ?? match[4] ?? '';
    attributes[match[1].toLowerCase()] = decodeEntities(value);
  }
  return attributes;
}

/**
 * Parses markup into a tree of `{type: 'element', name, attributes, children, parent}`
 * and `{type: 'text', text, parent}`. Comments are kept aside on the root.
 */
export function parseHtml(html) {
  const root = {type: 'element', name: '#root', attributes: {}, children: [], parent: null, comments: []};
  let current = root;
  TOKEN.lastIndex = 0;
  while (TOKEN.lastIndex < html.length) {
    const offset = TOKEN.lastIndex;
    const match = TOKEN.exec(html);
    if (match === null) {
      throw new UsageError(`cannot read the markup at offset ${offset}: ${JSON.stringify(html.slice(offset, offset + 40))}`);
    }
    const [whole, closeName, openName, attributeText, selfClosing, text] = match;
    if (whole.startsWith('<!--')) {
      root.comments.push(collapse(whole.slice(4, -3)));
    } else if (text !== undefined) {
      current.children.push({type: 'text', text: decodeEntities(text), parent: current});
    } else if (closeName !== undefined) {
      const name = closeName.toLowerCase();
      if (current.name !== name) {
        throw new UsageError(`</${name}> at offset ${offset} closes <${current.name}>; the markup is not well formed`);
      }
      current = current.parent;
    } else if (openName !== undefined) {
      const element = {
        type: 'element',
        name: openName.toLowerCase(),
        attributes: parseAttributes(attributeText),
        children: [],
        parent: current,
      };
      current.children.push(element);
      if (!VOID_ELEMENTS.has(element.name) && selfClosing !== '/') {
        current = element;
      }
    }
  }
  if (current !== root) {
    throw new UsageError(`<${current.name}> is never closed`);
  }
  return root;
}

function classesOf(element) {
  return (element.attributes.class ?? '').split(/\s+/).filter(Boolean);
}

function hasClass(element, name) {
  return classesOf(element).includes(name);
}

function* descendants(node) {
  for (const child of node.children) {
    yield child;
    if (child.type === 'element') {
      yield* descendants(child);
    }
  }
}

function find(root, predicate) {
  return [...descendants(root)].filter((node) => node.type === 'element' && predicate(node));
}

function elementChildren(element) {
  return element.children.filter((child) => child.type === 'element');
}

function textContent(node) {
  return node.type === 'text' ? node.text : node.children.map(textContent).join('');
}

/** Every text node under an element, one space apart: for messages, where adjacent elements should not run together. */
function spacedText(element) {
  return collapse([...descendants(element)].filter((node) => node.type === 'text').map((node) => node.text).join(' '));
}

/** HTML's whitespace collapsing: ASCII whitespace only, so a no-break or thin space stays itself. */
function collapse(text) {
  return text.replace(/[ \t\n\r\f]+/g, ' ').replace(/^ | $/g, '');
}

function pathOf(element) {
  const steps = [];
  for (let node = element; node !== null && node.name !== '#root'; node = node.parent) {
    const id = node.attributes.id ? `#${node.attributes.id}` : '';
    const classes = classesOf(node).map((name) => `.${name}`).join('');
    steps.unshift(`${node.name}${id}${classes}`);
  }
  return steps.join(' > ');
}

/**
 * Reads an element's content as inline parts: `{text}` for text, `{br: true}`
 * for a line break and `{tag}` for any other element, which no field of this
 * deck contains. Marks every text node read as claimed.
 */
function inlineParts(element, claimed) {
  const parts = [];
  for (const child of element.children) {
    if (child.type === 'text') {
      claimed.add(child);
      parts.push({text: child.text});
    } else if (child.name === 'br') {
      parts.push({br: true});
    } else {
      parts.push({tag: child.name});
      for (const node of descendants(child)) {
        if (node.type === 'text') {
          claimed.add(node);
        }
      }
    }
  }
  return parts;
}

/** Inline parts written the way D55 writes them in the manifest. */
export function partsToSource(parts) {
  return parts.map((part) => (part.br ? HARD_BREAK : part.tag ? `<${part.tag}>` : part.text)).join('');
}

/** Inline parts written as markup, for comparison and for messages. */
export function partsToMarkup(parts) {
  return parts.map((part) => (part.br ? '<br>' : part.tag ? `<${part.tag}>` : part.text)).join('');
}

/** Rendered inline HTML as parts, compared as they are: the product writes a hard break as a bare <br> (D164). */
function renderedParts(html) {
  const parts = inlineParts(parseHtml(html), new Set());
  return parts.filter((part) => part.text !== '');
}

