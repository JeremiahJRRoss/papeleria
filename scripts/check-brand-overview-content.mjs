/**
 * M1.9, content half: examples/brand-overview carries the text of
 * reference/decks/brand-overview.html, slide for slide.
 *
 * The reference is read with a small regex tokenizer and tree builder, not a
 * DOM library. Every field the manifest writes is compared twice:
 *
 * - at source level, the value must equal the reference text with entities
 *   decoded and each <br> written as the D55 hard break, a backslash ending
 *   the line;
 * - at render level, the product's own Markdown functions (`renderInlineMarkdown`
 *   for titles and leads, `renderMarkdown` for column text and notes, from the
 *   built core, D162) must reproduce the reference fragment exactly, <br> for
 *   <br> and a column as one paragraph, so nothing in the text becomes markup
 *   the kit did not have. Plain-string fields must come through unchanged as
 *   well, so the result does not depend on whether the renderer treats them as
 *   Markdown, and enabling markdown-it's typographer must change nothing.
 *
 * Before any of that, the piece must resolve through the product with no
 * finding at all, so a piece the product would refuse — a linked notes file,
 * say — cannot pass here.
 *
 * The render level needs the core compiled: run `npm run build` first. CI and
 * `npm test` build before they run this check.
 *
 * A notes file must hold its aside's text without the template label, one
 * paragraph per reference line.
 *
 * Every text node in the reference is accounted for: compared with a manifest
 * field, matched to documented template content (the notes label, the footer
 * counter, the wordmark, the type and wordmark samples), or listed as page
 * chrome outside the slides. A text node that nothing claims is a difference,
 * so reference content the manifest cannot express is reported, not skipped.
 *
 * This is the content half of M1.9 only. The A4 golden test, which compares
 * the built deck with the reference in a browser, belongs to W2B.
 *
 * Usage: node scripts/check-brand-overview-content.mjs [--piece <dir>] [--reference <file>]
 * Exit:  0 no difference · 1 one or more differences · 2 usage, IO, input that cannot be parsed, or no built core
 */
