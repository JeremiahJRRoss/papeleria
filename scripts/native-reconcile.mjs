#!/usr/bin/env node
/**
 * Reconciles three separate things for the native and platform packages (D34).
 *
 *   requirements   derived from the lockfile intersected with the documented
 *                  distribution scope in scripts/native-scope.json. Nobody can
 *                  drop a platform by editing a review: dropping one means
 *                  editing the scope file, which names a decision and an approver.
 *                  Nor can that edit empty the review: a package-pattern
 *                  exclusion may not match a package a platform in scope
 *                  requires, and sharp, which npm installs everywhere, stays
 *                  required whatever the scope lists (D177).
 *   observations   generated by scripts/native-inventory.mjs. What is actually
 *                  in a package: versions, integrity, artefact and licence-text
 *                  hashes, bundled components. Machine-written, per platform,
 *                  merged and never wholesale-replaced.
 *   reviews        compliance decisions made by a person. Never machine-written.
 *                  A review is bound to the artefact digests it was made against,
 *                  so a changed binary invalidates it instead of inheriting it.
 *
 * The separation is the point. Finding a licence file is an observation; deciding
 * that the LGPL obligations are met is a review, and only the second can clear a
 * release. A generator that could write reviews would be a generator that could
 * approve its own work.
 *
 * Exported for scripts/license-check.mjs; also runnable for a standalone report.
 */
import {existsSync, readFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {pathToFileURL} from 'node:url';

export class NativeConfigError extends Error {}

/** Packages that must be reviewed wherever the project distributes them. */
const NATIVE_PACKAGE_PATTERN = /^(@img\/sharp-|sharp$)/;

/** A review must answer all of these before it may say "verified". */
export const REQUIRED_REVIEW_EVIDENCE = [
  'licenseTextsRetained',
  'sourceAvailability',
  'linkingPosition',
];

const ISO_DATE = /^\d{4}-\d{2}-\d{2}$/;

function readJson(file, label) {
  if (!existsSync(file)) {
    return null;
  }
  try {
    return JSON.parse(readFileSync(file, 'utf8'));
  } catch (cause) {
    throw new NativeConfigError(`cannot parse ${label} ${file}: ${cause.message}`);
  }
}

// ------------------------------------------------------------------ scope ---

export function readScope(file) {
  const parsed = readJson(file, 'the distribution scope');
  if (parsed === null) {
    throw new NativeConfigError(
      `no distribution scope at ${file}; the release check cannot decide which platforms are ` +
        'required without one, and guessing would defeat the point of having it',
    );
  }
  const scope = parsed.distributionScope;
  if (typeof scope !== 'object' || scope === null || !Array.isArray(scope.platforms)) {
    throw new NativeConfigError(`${file}: distributionScope.platforms must be an array`);
  }
  for (const field of ['decision', 'authorizedBy', 'date']) {
    if (typeof scope[field] !== 'string' || scope[field].trim() === '') {
      throw new NativeConfigError(`${file}: distributionScope needs a non-empty ${field}`);
    }
  }
  for (const platform of scope.platforms) {
    for (const field of ['os', 'cpu', 'rationale']) {
      if (typeof platform[field] !== 'string' || platform[field].trim() === '') {
        throw new NativeConfigError(`${file}: every platform needs a non-empty ${field}`);
      }
    }
  }
  const exclusions = Array.isArray(parsed.exclusions) ? parsed.exclusions : [];
  for (const exclusion of exclusions) {
    for (const field of ['reason', 'decision', 'approvedBy', 'date']) {
      if (typeof exclusion[field] !== 'string' || exclusion[field].trim() === '') {
        throw new NativeConfigError(
          `${file}: every exclusion needs a non-empty ${field}; an exclusion is a recorded ` +
            'decision, not an omission',
        );
      }
    }
    if (typeof exclusion.match !== 'object' || exclusion.match === null) {
      throw new NativeConfigError(`${file}: every exclusion needs a match object`);
    }
  }
  return {scope, exclusions, file};
}

/** An exclusion by name: its pattern, on every platform at once. */
function excludesByName(exclusion, packageName) {
  const pattern = exclusion.match.packagePattern;
  return typeof pattern === 'string' && new RegExp(pattern).test(packageName);
}

/** An exclusion by platform: an os, a cpu or both, the way D34 has a platform leave scope. */
function excludesPlatform(exclusion, {os, cpu}) {
  const match = exclusion.match;
  if (match.os === undefined && match.cpu === undefined) {
    return false;
  }
  const osMatches = match.os === undefined || (os ?? []).includes(match.os);
  const cpuMatches = match.cpu === undefined || (cpu ?? []).includes(match.cpu);
  return osMatches && cpuMatches;
}

function excluded(exclusions, {packageName, os, cpu}) {
  return exclusions.find((exclusion) => excludesByName(exclusion, packageName) || excludesPlatform(exclusion, {os, cpu}));
}

/** Where a package with no os or cpu constraint is installed: with Papeleria, everywhere. */
const EVERY_PLATFORM = Object.freeze({os: 'any-os', cpu: 'any-cpu', rationale: 'npm installs it on every platform'});

function supported(platforms, {os, cpu}) {
  // A package with no os/cpu constraint (sharp, @img/sharp-wasm32) is installed
  // wherever Papeleria is, so it is required whatever the platform list says,
  // and no edit to the scope can take it out of the review (D177).
  if (os === undefined && cpu === undefined) {
    return EVERY_PLATFORM;
  }
  return (
    platforms.find(
      (platform) =>
        (os === undefined || os.includes(platform.os)) &&
        (cpu === undefined || cpu.includes(platform.cpu)),
    ) ?? null
  );
}

// ----------------------------------------------------------- requirements ---

/**
 * What the current lockfile says must be reviewed, given the documented scope.
 * Derived, never hand-maintained: a new sharp platform package appears here the
 * moment npm locks it.
 */
export function deriveRequirements({root, scope, exclusions, file = 'the distribution scope'}) {
  const lockPath = join(root, 'package-lock.json');
  const lock = readJson(lockPath, 'the lockfile');
  if (lock === null) {
    throw new NativeConfigError(`no package-lock.json under ${root}`);
  }
  const requirements = [];
  for (const [path, entry] of Object.entries(lock.packages ?? {})) {
    if (!path) continue;
    const packageName =
      entry.name ?? path.slice(path.lastIndexOf('node_modules/') + 'node_modules/'.length);
    if (!NATIVE_PACKAGE_PATTERN.test(packageName)) continue;

    const os = Array.isArray(entry.os) ? entry.os : undefined;
    const cpu = Array.isArray(entry.cpu) ? entry.cpu : undefined;
    const platform = supported(scope.platforms, {os, cpu});
    // A pattern names a package on every platform at once, so one broad pattern
    // could take every requirement out of the review and leave the release gate
    // green with nothing signed (W5R-30). It may name only a package that no
    // platform in scope requires, whatever decision it cites; a platform leaves
    // scope through an os/cpu exclusion, as D34 has it (D177).
    if (platform !== null && !exclusions.some((candidate) => excludesPlatform(candidate, {os, cpu}))) {
      const byName = exclusions.find((candidate) => excludesByName(candidate, packageName));
      if (byName !== undefined) {
        const where = platform === EVERY_PLATFORM ? 'npm installs on every platform' : `${platform.os}/${platform.cpu} in scope requires`;
        throw new NativeConfigError(
          `${file}: the exclusion ${JSON.stringify(byName.match.packagePattern)} (${byName.decision}) matches ${packageName}, which ${where}; ` +
            'a package-pattern exclusion may name only packages no platform in scope requires, whatever decision it cites (D177). ' +
            'A platform leaves scope through an os/cpu exclusion naming a decision, an approver and a date (D34)',
        );
      }
    }
    const exclusion = excluded(exclusions, {packageName, os, cpu});

    requirements.push({
      package: packageName,
      version: entry.version ?? null,
      integrity: entry.integrity ?? null,
      declaredLicense: entry.license ?? null,
      os: os ?? null,
      cpu: cpu ?? null,
      platformKey: `${(os ?? ['any-os']).join('|')}/${(cpu ?? ['any-cpu']).join('|')}`,
      required: platform !== null && exclusion === undefined,
      excludedBy: exclusion
        ? {reason: exclusion.reason, decision: exclusion.decision, approvedBy: exclusion.approvedBy}
        : null,
    });
  }
  requirements.sort((a, b) => (a.package < b.package ? -1 : a.package > b.package ? 1 : 0));
  return requirements;
}

// ----------------------------------------------------------- observations ---

export function readObservations(file) {
  const parsed = readJson(file, 'the native observations');
  if (parsed === null) {
    return {records: [], present: false, file};
  }
  const records = Array.isArray(parsed.observations) ? parsed.observations : null;
  if (records === null) {
    throw new NativeConfigError(`${file}: "observations" must be an array`);
  }
  const seen = new Map();
  for (const record of records) {
    for (const field of ['package', 'version', 'platformKey', 'inspection', 'observedFrom', 'observedOn']) {
      if (typeof record[field] !== 'string' || record[field].trim() === '') {
        throw new NativeConfigError(`${file}: an observation is missing ${field}`);
      }
    }
    if (!['installed', 'fetched-package'].includes(record.inspection)) {
      throw new NativeConfigError(
        `${file}: ${record.package} has inspection ${JSON.stringify(record.inspection)}; use ` +
          '"installed" (present on the inspecting platform) or "fetched-package" (the published ' +
          'tarball unpacked and read without running it)',
      );
    }
    if (!ISO_DATE.test(record.observedOn)) {
      throw new NativeConfigError(`${file}: ${record.package} has observedOn ${JSON.stringify(record.observedOn)}; use YYYY-MM-DD`);
    }
    const key = observationKey(record);
    const previous = seen.get(key);
    if (previous !== undefined && previous.artefactDigest !== record.artefactDigest) {
      throw new NativeConfigError(
        `${file}: two observations of ${record.package}@${record.version} on ${record.platformKey} ` +
          `via ${record.inspection} disagree about the artefact digest`,
      );
    }
    seen.set(key, record);
  }
  return {records, present: true, file};
}

/** Identity of one observation: the same package, version, platform and method. */
export function observationKey(record) {
  return `${record.package}@${record.version}|${record.platformKey}|${record.inspection}`;
}

/**
 * A stable digest of what was actually inspected, so a review can be bound to it.
 * Changing a binary or a licence text changes this, which invalidates the review.
 */
export function artefactDigestOf(record) {
  const parts = [
    record.integrity ?? '',
    ...(record.nativeArtefacts ?? []).map((a) => `${a.path}:${a.sha256}`).sort(),
    ...(record.licenseFiles ?? []).map((f) => `${f.path}:${f.sha256}`).sort(),
  ];
  return parts.join('\n');
}

/**
 * Merges freshly generated observations into the existing set.
 *
 * Deterministic and additive: a record is replaced only by a record with the same
 * identity. A Windows scan therefore adds Windows rows and leaves the Linux and
 * macOS rows exactly as they were, which is the whole reason observations are a
 * separate file from reviews.
 */
export function mergeObservations(existing, fresh) {
  const byKey = new Map(existing.map((record) => [observationKey(record), record]));
  const replaced = [];
  const added = [];
  // "replaced" means the bytes moved, which invalidates a review bound to them.
  // "rewritten" means the same bytes were read again and the record came out
  // different — a better reader, a new field. Reporting them together would
  // either cry wolf about reviews or hide that the file changed at all.
  const rewritten = [];
  const freshKeys = new Set();
  for (const record of fresh) {
    const key = observationKey(record);
    freshKeys.add(key);
    if (byKey.has(key)) {
      const previous = byKey.get(key);
      if (artefactDigestOf(previous) !== artefactDigestOf(record)) {
        replaced.push(key);
      } else if (JSON.stringify(previous) !== JSON.stringify(record)) {
        rewritten.push(key);
      }
    } else {
      added.push(key);
    }
    byKey.set(key, record);
  }
  const merged = [...byKey.values()].sort((a, b) => {
    const left = observationKey(a);
    const right = observationKey(b);
    return left < right ? -1 : left > right ? 1 : 0;
  });
  // Kept means untouched by this run: observed on some other platform or in an
  // earlier one, and not re-read here. Counting everything that survived would
  // report a full re-read as if most of the file were inherited.
  const kept = existing.filter((record) => !freshKeys.has(observationKey(record))).length;
  return {merged, replaced, added, rewritten, kept};
}

// ---------------------------------------------------------------- reviews ---

/**
 * Facts a machine can assemble — a static linkage read, a retained licence text,
 * a published source location — recorded on an unresolved review so the reviewer
 * has them to hand.
 *
 * They are proposals, not findings. proposedEvidence never moves a review towards
 * verified and the release check keeps blocking until a person examines the facts,
 * moves the ones they accept into evidence, and signs the review. Assembling
 * evidence and accepting it are different acts; only the second is a decision, and
 * only a person makes it.
 */
function validateProposedEvidence(file, review) {
  const id = `${review.package}@${review.version}`;
  const proposed = review.proposedEvidence;
  if (typeof proposed !== 'object' || proposed === null || Array.isArray(proposed)) {
    throw new NativeConfigError(`${file}: ${id} has a proposedEvidence that is not an object`);
  }
  if (review.status === 'verified') {
    throw new NativeConfigError(
      `${file}: ${id} is verified but still carries proposedEvidence. Signing a review means ` +
        'moving the facts you accept into evidence, not leaving them beside it as proposals.',
    );
  }
  for (const field of ['assembledBy', 'assembledOn']) {
    if (typeof proposed[field] !== 'string' || proposed[field].trim() === '') {
      throw new NativeConfigError(
        `${file}: ${id} has proposedEvidence with no ${field}; assembled facts say who assembled ` +
          'them and when, or a reader cannot tell how old they are',
      );
    }
  }
  if (!ISO_DATE.test(proposed.assembledOn)) {
    throw new NativeConfigError(`${file}: ${id} has proposedEvidence with a malformed assembledOn`);
  }
  const known = new Set([...REQUIRED_REVIEW_EVIDENCE, 'assembledBy', 'assembledOn', 'sources']);
  for (const key of Object.keys(proposed)) {
    if (!known.has(key)) {
      throw new NativeConfigError(
        `${file}: ${id} has proposedEvidence.${key}, which is not one of ` +
          `${[...known].join(', ')}. A misspelled field would look like evidence and carry nothing.`,
      );
    }
  }
  const offered = REQUIRED_REVIEW_EVIDENCE.filter((field) => proposed[field] !== undefined);
  if (offered.length === 0) {
    throw new NativeConfigError(
      `${file}: ${id} has proposedEvidence that proposes none of ${REQUIRED_REVIEW_EVIDENCE.join(', ')}`,
    );
  }
  for (const field of offered) {
    if (typeof proposed[field] !== 'string' || proposed[field].trim() === '') {
      throw new NativeConfigError(`${file}: ${id} has an empty proposedEvidence.${field}`);
    }
  }
  // A proposal that points at a file which is no longer in the repository is
  // worse than no proposal: it reads as evidence and holds none. Checking the
  // paths here means deleting licenses/ or the source index breaks the run
  // rather than quietly hollowing out sixteen reviews.
  //
  // The paths are relative to the reviews file, not to --root: --root is the
  // installed tree being inspected, which on a release check may be a different
  // checkout or a temporary one, while the assembled facts live beside the
  // reviews that cite them.
  if (proposed.sources !== undefined) {
    if (!Array.isArray(proposed.sources) || proposed.sources.length === 0) {
      throw new NativeConfigError(`${file}: ${id} has proposedEvidence.sources that is not a non-empty array`);
    }
    for (const source of proposed.sources) {
      if (typeof source !== 'string' || source.trim() === '') {
        throw new NativeConfigError(`${file}: ${id} has an empty entry in proposedEvidence.sources`);
      }
      if (!existsSync(join(dirname(file), source))) {
        throw new NativeConfigError(
          `${file}: ${id} proposes evidence from ${source}, which does not exist. Assembled facts ` +
            'must still be in the repository, or the proposal points at nothing.',
        );
      }
    }
  }
}

export function readReviews(file) {
  const parsed = readJson(file, 'the native reviews');
  if (parsed === null) {
    return {records: [], present: false, file};
  }
  const records = Array.isArray(parsed.reviews) ? parsed.reviews : null;
  if (records === null) {
    throw new NativeConfigError(`${file}: "reviews" must be an array`);
  }
  const seen = new Set();
  for (const review of records) {
    for (const field of ['package', 'version', 'status', 'reviewedBy', 'reviewedOn']) {
      if (typeof review[field] !== 'string' || review[field].trim() === '') {
        throw new NativeConfigError(`${file}: a review is missing ${field}`);
      }
    }
    if (!['verified', 'unresolved'].includes(review.status)) {
      throw new NativeConfigError(
        `${file}: ${review.package}@${review.version} has status ${JSON.stringify(review.status)}; ` +
          'use "verified" or "unresolved"',
      );
    }
    if (!ISO_DATE.test(review.reviewedOn)) {
      throw new NativeConfigError(`${file}: ${review.package}@${review.version} has a malformed reviewedOn`);
    }
    const key = `${review.package}@${review.version}|${review.platformKey ?? 'all'}`;
    if (seen.has(key)) {
      throw new NativeConfigError(`${file}: ${key} is reviewed twice`);
    }
    seen.add(key);

    if (review.proposedEvidence !== undefined) {
      validateProposedEvidence(file, review);
    }

    if (review.status === 'verified') {
      for (const field of REQUIRED_REVIEW_EVIDENCE) {
        const value = review.evidence?.[field];
        if (typeof value !== 'string' || value.trim() === '') {
          throw new NativeConfigError(
            `${file}: ${review.package}@${review.version} is verified but records no ${field}. ` +
              'A verified review states where the licence texts are retained, where corresponding ' +
              'source is offered, and whether the artefact is linked statically or dynamically.',
          );
        }
      }
      if (typeof review.boundToArtefactDigest !== 'string' || review.boundToArtefactDigest.trim() === '') {
        throw new NativeConfigError(
          `${file}: ${review.package}@${review.version} is verified but is not bound to an ` +
            'artefact digest, so a changed binary would inherit the review',
        );
      }
    }
  }
  return {records, present: true, file};
}

// ------------------------------------------------------------ reconcile -----

/**
 * Returns {problems, rows}. A problem blocks a release; the rows are the report.
 */
export function reconcileNative({root, scopeFile, observationsFile, reviewsFile}) {
  const {scope, exclusions, file} = readScope(scopeFile);
  const requirements = deriveRequirements({root, scope, exclusions, file});
  const observations = readObservations(observationsFile);
  const reviews = readReviews(reviewsFile);

  const problems = [];
  const rows = [];

  const observationsByPackage = new Map();
  for (const record of observations.records) {
    const list = observationsByPackage.get(`${record.package}@${record.version}`) ?? [];
    list.push(record);
    observationsByPackage.set(`${record.package}@${record.version}`, list);
  }

  // An observation whose version is not in the lockfile at all is stale data.
  const lockedVersions = new Set(requirements.map((r) => `${r.package}@${r.version}`));
  for (const record of observations.records) {
    if (!lockedVersions.has(`${record.package}@${record.version}`)) {
      problems.push(
        `observation for ${record.package}@${record.version} does not match any locked version; ` +
          'the lockfile moved and the observation was not regenerated',
      );
    }
  }
  for (const review of reviews.records) {
    if (!lockedVersions.has(`${review.package}@${review.version}`)) {
      problems.push(
        `review for ${review.package}@${review.version} does not match any locked version; ` +
          'a review cannot carry forward to a version nobody reviewed',
      );
    }
  }

  for (const requirement of requirements) {
    const id = `${requirement.package}@${requirement.version}`;
    const seen = observationsByPackage.get(id) ?? [];
    const review = reviews.records.find(
      (candidate) => candidate.package === requirement.package && candidate.version === requirement.version,
    );

    const row = {
      package: requirement.package,
      version: requirement.version,
      platformKey: requirement.platformKey,
      required: requirement.required,
      excludedBy: requirement.excludedBy,
      observations: seen.map((record) => record.inspection),
      reviewStatus: review?.status ?? 'absent',
      state: 'ok',
      detail: '',
    };

    if (!requirement.required) {
      row.state = 'out-of-scope';
      row.detail = requirement.excludedBy?.reason ?? 'no supported platform matches this package';
      rows.push(row);
      continue;
    }

    // A missing observation and a missing review are independent gaps. Report
    // both rather than stopping at the first, so a reader learns everything the
    // package still needs in one run.
    if (seen.length === 0) {
      row.state = 'no-observation';
      row.detail = 'no observation on any platform; run scripts/native-inventory.mjs';
      problems.push(`${id} (${requirement.platformKey}) has no observation at all`);
      if (review === undefined) {
        problems.push(`${id} (${requirement.platformKey}) has no compliance review`);
      }
      rows.push(row);
      continue;
    }

    // Integrity must match the lockfile, or the bytes inspected are not the
    // bytes npm will install.
    for (const record of seen) {
      if (
        requirement.integrity !== null &&
        record.integrity !== undefined &&
        record.integrity !== null &&
        record.integrity !== requirement.integrity
      ) {
        row.state = 'integrity-mismatch';
        problems.push(
          `${id} was observed with integrity ${record.integrity} but the lockfile records ` +
            `${requirement.integrity}`,
        );
      }
    }

    if (review === undefined) {
      row.state = row.state === 'ok' ? 'no-review' : row.state;
      row.detail = 'no compliance review recorded';
      problems.push(`${id} (${requirement.platformKey}) has no compliance review`);
      rows.push(row);
      continue;
    }

    if (review.status !== 'verified') {
      row.state = 'unresolved';
      row.detail = review.unresolved ?? 'the review is not complete';
      row.proposedEvidence = REQUIRED_REVIEW_EVIDENCE.filter(
        (field) => review.proposedEvidence?.[field] !== undefined,
      );
      problems.push(`${id} review is ${review.status}: ${row.detail}`);
      rows.push(row);
      continue;
    }

    // A verified review is bound to what was inspected. If the artefacts moved,
    // the review no longer describes them.
    const currentDigests = seen.map((record) => artefactDigestOf(record));
    if (!currentDigests.includes(review.boundToArtefactDigest)) {
      row.state = 'review-invalidated';
      row.detail = 'the artefacts changed since the review was made';
      problems.push(
        `${id} is marked verified, but no current observation matches the artefact digest the ` +
          'review was bound to; re-review the changed binary',
      );
      rows.push(row);
      continue;
    }

    row.detail = `verified ${review.reviewedOn} by ${review.reviewedBy}`;
    rows.push(row);
  }

  if (!observations.present) {
    problems.push(
      `no native observations at ${observations.file}; run scripts/native-inventory.mjs before a release`,
    );
  }
  if (!reviews.present) {
    problems.push(
      `no native reviews at ${reviews.file}; the compliance decisions are a person's to record`,
    );
  }

  return {
    problems,
    rows,
    requirements,
    observations,
    reviews,
    scope,
    counts: {
      required: requirements.filter((r) => r.required).length,
      outOfScope: requirements.filter((r) => !r.required).length,
      observed: observations.records.length,
      verified: rows.filter((r) => r.required && r.state === 'ok').length,
      awaitingSignature: rows.filter(
        (r) => r.required && r.state === 'unresolved' && (r.proposedEvidence?.length ?? 0) > 0,
      ).length,
    },
  };
}

function main(argv) {
  const root = argv[0] ?? process.cwd();
  const here = import.meta.dirname;
  try {
    const result = reconcileNative({
      root,
      scopeFile: join(here, 'native-scope.json'),
      observationsFile: join(here, 'native-observations.json'),
      reviewsFile: join(here, 'native-reviews.json'),
    });
    process.stdout.write(
      `native reconciliation: ${result.counts.required} required, ` +
        `${result.counts.verified} verified, ${result.counts.outOfScope} out of scope, ` +
        `${result.counts.observed} observation(s)\n`,
    );
    if (result.counts.awaitingSignature > 0) {
      process.stdout.write(
        `  ${result.counts.awaitingSignature} unresolved review(s) carry assembled facts awaiting a ` +
          "reviewer's signature; assembled facts are not a finding and do not clear the release\n",
      );
    }
    for (const problem of result.problems) {
      process.stdout.write(`  blocker ${problem}\n`);
    }
    return result.problems.length === 0 ? 0 : 1;
  } catch (error) {
    process.stderr.write(`native-reconcile: ${error.message}\n`);
    return 2;
  }
}

const entryPath = process.argv[1];
if (entryPath !== undefined && import.meta.url === pathToFileURL(entryPath).href) {
  process.exitCode = main(process.argv.slice(2));
}
